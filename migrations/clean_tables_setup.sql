CREATE TABLE IF NOT EXISTS maqams (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  malayalam_name TEXT,
  location TEXT NOT NULL,
  city TEXT NOT NULL,
  country TEXT NOT NULL DEFAULT 'India',
  region TEXT NOT NULL DEFAULT 'kerala',
  category TEXT NOT NULL DEFAULT 'scholar',
  era TEXT,
  description TEXT NOT NULL,
  significance TEXT,
  best_time_to_visit TEXT,
  source_url TEXT,
  cover_image TEXT,
  address_detail TEXT,
  visiting_hours TEXT,
  facilities TEXT,
  how_to_reach TEXT,
  contact_info TEXT,
  history TEXT,
  architecture TEXT,
  created_from_request_id TEXT,
  status TEXT NOT NULL DEFAULT 'published' CHECK (status IN ('published', 'draft', 'archived')),
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

CREATE TABLE IF NOT EXISTS uroos (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  malayalam_title TEXT,
  maqam_id TEXT,
  is_standalone INTEGER NOT NULL DEFAULT 0,
  resting_person TEXT,
  hijri_month INTEGER,
  hijri_month_name TEXT,
  hijri_day INTEGER,
  gregorian_date TEXT,
  recurrence TEXT,
  venue_name TEXT,
  city TEXT,
  state TEXT DEFAULT 'Kerala',
  country TEXT DEFAULT 'India',
  description TEXT NOT NULL,
  history TEXT,
  significance TEXT,
  program_schedule TEXT,
  nercha_offerings TEXT,
  how_to_reach TEXT,
  organizer_name TEXT,
  organizer_contact TEXT,
  cover_image TEXT,
  source_url TEXT,
  created_from_request_id TEXT,
  status TEXT NOT NULL DEFAULT 'published' CHECK (status IN ('published', 'draft', 'archived')),
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  FOREIGN KEY (maqam_id) REFERENCES maqams(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS page_allotments (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  user_email TEXT NOT NULL,
  target_type TEXT NOT NULL CHECK (target_type IN ('maqam', 'uroos')),
  target_id TEXT NOT NULL,
  target_title TEXT NOT NULL,
  assigned_by TEXT NOT NULL,
  assigned_by_email TEXT,
  notes TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  UNIQUE(user_id, target_type, target_id)
);

CREATE TABLE IF NOT EXISTS system_roles (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL UNIQUE,
  user_email TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'admin' CHECK (role IN ('super_admin', 'admin', 'user')),
  display_name TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
